PAGE = 0
W, H = A4
Y = 0

def start(title, wide=False):
    global PAGE, W, H, Y
    if PAGE:
        finish()
    PAGE += 1
    W, H = landscape(A4) if wide else A4
    C.setPageSize((W, H))
    C.setFillColor(HexColor('#126b75'))
    C.rect(36, H - 43, W - 72, 3, fill=1, stroke=0)
    C.setFont('ArialB', 14)
    C.setFillColor(HexColor('#172637'))
    C.drawString(36, H - 69, title)
    Y = H - 91

def finish():
    assert Y >= 36, (PAGE, Y)
    C.setFont('Arial', 8)
    C.setFillColor(HexColor('#607080'))
    C.drawString(36, 22, 'ЛР3 | Ананьев Н.А. | ИУ7-55Б | измерения в QEMU TCG')
    C.drawRightString(W - 36, 22, str(PAGE))
    C.showPage()

def p(text, small=False):
    global Y
    para = Paragraph(text, SMALL if small else STYLE)
    _, height = para.wrap(W - 72, H)
    para.drawOn(C, 36, Y - height)
    Y -= height + 9

def table(rows, widths=None):
    global Y
    vals = [[Paragraph(escape(str(v)), SMALL) for v in row] for row in rows]
    t = Table(vals, colWidths=widths or [(W - 72) / len(rows[0])] * len(rows[0]))
    t.setStyle(TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), HexColor('#dceff0')),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [white, HexColor('#f3f6f8')]),
        ('VALIGN', (0, 0), (-1, -1), 'TOP'),
        ('LEFTPADDING', (0, 0), (-1, -1), 7),
        ('RIGHTPADDING', (0, 0), (-1, -1), 7),
        ('TOPPADDING', (0, 0), (-1, -1), 6),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 6),
        ('LINEBELOW', (0, 0), (-1, 0), 0.6, HexColor('#a7c8cb')),
    ]))
    _, height = t.wrap(W - 72, H)
    t.drawOn(C, 36, Y - height)
    Y -= height + 12

def pic(path, max_height=240):
    global Y
    iw, ih = Image.open(path).size
    scale = min((W - 72) / iw, max_height / ih)
    width, height = iw * scale, ih * scale
    C.drawImage(str(path), (W - width) / 2, Y - height, width=width, height=height)
    Y -= height + 9

def plot(i):
    global Y
    rows = [[float(v) for v in row] for row in list(csv.reader((ROOT / f'output/data/exp{i}.csv').open()))[1:]]
    width, height = W - 72, 205
    drawing = Drawing(width, height)
    lp = LinePlot()
    lp.x, lp.y, lp.width, lp.height = 55, 32, width - 70, 148
    lp.data = [[(row[0], row[col]) for row in rows] for col in range(1, len(rows[0]))]
    colors = ['#d63232', '#168546'] if i != 6 else ['#8a37bf', '#d63232', '#168546']
    for k, color in enumerate(colors[:len(lp.data)]):
        lp.lines[k].strokeColor = HexColor(color)
        lp.lines[k].strokeWidth = 1
    for axis in [lp.xValueAxis, lp.yValueAxis]:
        axis.labels.fontName = 'Arial'
        axis.labels.fontSize = 8
        axis.visibleGrid = True
        axis.gridStrokeColor = HexColor('#dce3e7')
        axis.gridStrokeWidth = 0.3
        axis.valueMin = 0
        axis.maximumTicks = 6
        axis.labelTextFormat = lambda val: f'{val:g}' if abs(val) < 1000 else f'{val/1000:g}k'
    drawing.add(lp)
    drawing.add(String(0, 191, 'Время, мкс', fontName='Arial', fontSize=8))
    xlabel = {1:'Шаг, Б',2:'Фрагментация, К (ось PCLAB)',3:'Смещение, Б',4:'Потоки данных',5:'Номер обращения',6:'Элементы'}[i]
    drawing.add(String(width/2, 1, xlabel, fontName='Arial', fontSize=8, textAnchor='middle'))
    renderPDF.draw(drawing, C, 36, Y-height)
    Y -= height + 9

def num(x):
    return f'{x:,.3f}'.replace(',', ' ').replace('.', ',')

def ratio(i, j=0):
    return DATA[f'exp{i}']['ratios_of_sums'][j]

def samples(i):
    rows = list(csv.reader((ROOT / f'output/data/exp{i}.csv').open()))[1:]
    idx = sorted(set([0, len(rows)//4, len(rows)//2, 3*len(rows)//4, len(rows)-1]))
    return [[f'{int(float(rows[k][0])):,}'.replace(',', ' ')] + [num(float(v)) for v in rows[k][1:]] for k in idx]

